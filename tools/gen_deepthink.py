H1("五、需求4：剪切扩展至所有图元类型")
P("目标：剪切不再局限于直线，要支持直线、圆、圆弧、多边形、矩形等各类图元；剪切边界可基于其他图元或指定边界线。"
  "底层由 trim::trimElement 统一调度，按类型分发，且继承被剪图元的样式与图层。")

H2("5.1 剪切语义：移除「点中的那一跨」")
P("对齐主流 CAD（AutoCAD/SolidWorks）的关键决策：剪切只移除鼠标点中的那一段，而不是在每处交点都切碎图元。"
  "这由 splitPolyline 实现——按累积弧长参数定位交叉点，丢弃包含点击点的区间，返回剩余段。")
bullet("折线族（直线/矩形/多边形/样条）：统一离散成顶点序列后做弧长参数化剪切。")
bullet("圆/圆弧：用角度参数化而非弧长，trimArc 把圆周/弧按交点角度切分并取不含点击点的那段。")
bullet("矩形/多边形被剪后必然是开放折线，故 closed 是「数据字段」而非「类型固有属性」；矩形失去矩形性后降级为多边形。")

H2("5.2 边界的两种来源，算法完全一致")
P("快速剪切（不指定边界）：把场景中其余全部可见几何图元当作边界；显式剪切：只把用户点选的若干图元当边界。"
  "两者的差别仅仅是传入 trimElement 的 cutters 集合不同，求交→参数化→切分→重建的链路完全相同。"
  "约束与标注是注释性图元，不参与几何求交，gatherCuts 会跳过它们。")

H2("5.3 继承而非重建样式")
P("剪出的新图元由 inherit() 复制源图元的 name/layer/color/lineWidth/visible，只换几何——剪切不应改变颜色或线宽。"
  "自测用 lineWidth=3、红色的直线验证，剪后仍保留 3px 红。")

H2("5.4 替换的原子性（replaceElement）")
P("剪切在模型层表现为「删 1 加 N」，用 replaceElement 合并为一次快照：删除目标、在原 z 序位置插入新段、更新选中、"
  "只压一次撤销记录。整段剪切/回退是单一事务，不会因多次快照污染撤销栈。")

