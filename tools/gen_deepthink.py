H1("四、需求3：图元端点拖拽联动（保持拓扑）")
P("目标：选中图元后，若鼠标捕捉到端点并拖动，所有以该端点为连接点的图元应实时跟随，保持拓扑连接关系不变。"
  "这是 CAD「参数化草图」体验的核心：拖动一条线的端点，相接的线、矩形边应一起动，而不是断开。")

H2("4.1 拓扑 = 端点坐标重合")
P("我们刻意不引入「拓扑图」数据结构。原因：草图图元本就通过端点坐标重合来表达连接，"
  "引入独立拓扑图会与几何坐标产生第二份真相、还需要维护同步。直接用坐标重合判定连接，"
  "既是数据也是拓扑，零额外状态。collectLinked(p, tol) 收集所有落在容差内的控制点引用 "
  "HandleRef{elemId, index}，这就是「连接关系」的运行时表达。")

H2("4.2 为什么在「按下时」锁定联动集合")
P("关键陷阱：拖动过程中端点本身在移动，若每帧都重新收集「附近端点」，被拖动的点一旦移开原位置，"
  "原本相连的伙伴会因不再重合而「掉队」。解法：在 mousePress 时一次性 collectLinked 锁定 dragRefs_，"
  "整段拖拽都复用这一组引用。语义上完全正确——「我抓住的是这个连接点，以及所有共享它的图元」。")

H2("4.3 圆心（中心点）必须排除在联动之外")
P("圆/圆弧的「圆心」控制点若也参与联动，会导致「拖一条恰好过圆心的直线端点」时把圆整体拽走——"
  "这违背直觉。因此 collectLinked 显式跳过 Circle/Arc 的 index 0（中心）。"
  "自测特别构造了「圆 (0,0) 与两条直线的起点重合」的场景，断言 (0,0) 处的联动只含 2 个直线端点、不含圆心。")

H2("4.4 联动与撤销粒度同构")
P("联动移动复用 updateElementQuiet + moveHandles（一次遍历改写所有引用点、末尾发一次 modelChanged），"
  "配合按下时的 beginEdit，整段拖拽只产生一条撤销记录。这样「拖一条线带动三条线」可一键回退为整体操作。")

